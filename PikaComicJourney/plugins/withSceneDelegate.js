const fs = require('fs');
const path = require('path');
const { withInfoPlist, withXcodeProject, withDangerousMod, IOSConfig } = require('@expo/config-plugins');

// Apps built with the Xcode 27 iOS SDK must adopt the UIScene life cycle or
// iOS 27 refuses to launch them ("UIScene life cycle is required for apps
// built with this SDK"). Expo SDK 56's AppDelegate template still creates a
// scene-less UIWindow, so this plugin:
//   1. declares a single-window scene manifest in Info.plist, and
//   2. adds SceneDelegate.swift, which attaches the window AppDelegate already
//      started React Native in to the connected UIWindowScene.
// AppDelegate.swift is left untouched on purpose: @react-native-firebase/app
// anchors its `FirebaseApp.configure()` insertion on `factory.startReactNative(`.
const SCENE_DELEGATE_FILE = 'SceneDelegate.swift';

const SCENE_DELEGATE_SOURCE = `import UIKit
import React

// Generated by plugins/withSceneDelegate.js — edit the plugin, not this file.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate else {
      return
    }

    // AppDelegate started React Native in a window that has no scene and is
    // therefore never shown; attach that same window to the connected scene.
    let window = appDelegate.window ?? UIWindow(windowScene: windowScene)
    window.windowScene = windowScene
    window.frame = windowScene.coordinateSpace.bounds
    window.makeKeyAndVisible()
    self.window = window
    appDelegate.window = window

    if let url = connectionOptions.urlContexts.first?.url {
      _ = RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    _ = RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(UIApplication.shared, continue: userActivity) { _ in }
  }
}
`;

const withSceneManifest = (config) =>
  withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return config;
  });

const withSceneDelegateFile = (config) =>
  withDangerousMod(config, [
    'ios',
    async (config) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
      const filePath = path.join(config.modRequest.platformProjectRoot, projectName, SCENE_DELEGATE_FILE);
      fs.writeFileSync(filePath, SCENE_DELEGATE_SOURCE);
      return config;
    },
  ]);

const withSceneDelegateInProject = (config) =>
  withXcodeProject(config, (config) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: config.modResults,
      });
    }
    return config;
  });

function withSceneDelegate(config) {
  config = withSceneManifest(config);
  config = withSceneDelegateInProject(config);
  config = withSceneDelegateFile(config);
  return config;
}

module.exports = withSceneDelegate;
