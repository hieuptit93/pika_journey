#!/usr/bin/env node
/**
 * @react-native-firebase/app injects a "[RNFB] Embed Firebase SPM Frameworks"
 * build phase into the iOS project during `pod install`. That phase copies
 * every *.framework it finds under the shared Archive build-products folder
 * into the app bundle so genuine Firebase SPM frameworks get embedded — but
 * that folder is shared by the whole build graph, so it also catches
 * CocoaPods framework artifacts (ExpoAsset.framework, Pods_<target>.framework)
 * that must never be embedded standalone. App Store validation rejects
 * archives that contain them ("Invalid bundle structure").
 *
 * This patches the phase's shell script to skip anything that is a
 * CocoaPods target. It's run automatically after every `pod install` via
 * the Podfile's `post_integrate` hook (see plugins/withFixRnfbEmbedFrameworks.js),
 * since ios/ is regenerated by `expo prebuild` and not committed to git.
 */
const fs = require('fs');
const path = require('path');

const iosDir = path.join(__dirname, '..', 'ios');

function findPbxproj(dir) {
  if (!fs.existsSync(dir)) return null;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const xcodeproj = entries.find((e) => e.isDirectory() && e.name.endsWith('.xcodeproj'));
  if (!xcodeproj) return null;
  const pbxproj = path.join(dir, xcodeproj.name, 'project.pbxproj');
  return fs.existsSync(pbxproj) ? pbxproj : null;
}

const pbxprojPath = findPbxproj(iosDir);
if (!pbxprojPath) {
  console.warn('[fix-rnfb-embed-frameworks] No .xcodeproj found under ios/, skipping.');
  process.exit(0);
}

let contents = fs.readFileSync(pbxprojPath, 'utf8');

// NOTE: project.pbxproj stores the script as a single-line string with
// literal backslash-escaped quotes/newlines (plist string syntax), not real
// newline characters — the patterns below intentionally match that raw text.
const ALREADY_PATCHED_MARKER = 'Target Support Files/${framework_name%.framework}';
const OLD = 'framework_name=\\"$(basename \\"${framework}\\")\\"\\n    destination=\\"${app_frameworks_dir}/${framework_name}\\"';
const NEW =
  'framework_name=\\"$(basename \\"${framework}\\")\\"\\n\\n' +
  '    if [ -d \\"${PODS_ROOT}/Target Support Files/${framework_name%.framework}\\" ] || [[ \\"${framework_name}\\" == Pods_* ]] || [[ \\"${framework_name}\\" == Pods-* ]]; then\\n' +
  '      echo \\"Skipping ${framework_name} (CocoaPods target, not a Firebase SPM product)\\"\\n' +
  '      continue\\n' +
  '    fi\\n\\n' +
  '    destination=\\"${app_frameworks_dir}/${framework_name}\\"';

if (contents.includes(ALREADY_PATCHED_MARKER)) {
  console.log('[fix-rnfb-embed-frameworks] Already patched, nothing to do.');
  process.exit(0);
}

if (!contents.includes(OLD)) {
  console.warn(
    '[fix-rnfb-embed-frameworks] Could not find the expected "[RNFB] Embed Firebase SPM Frameworks" ' +
      'fragment (RNFB may not have added the phase, or the upstream script changed). Skipping — ' +
      'please re-check this fix if the "Invalid bundle structure" App Store error comes back.'
  );
  process.exit(0);
}

contents = contents.split(OLD).join(NEW);
fs.writeFileSync(pbxprojPath, contents);
console.log('[fix-rnfb-embed-frameworks] Patched project.pbxproj: RNFB SPM embed now skips CocoaPods targets.');
